export const dictionary = { tr, en };

let current = document.documentElement.getAttribute("lang") === "en" ? "en" : "tr";
const listeners = new Set();

export function getLang() {
  return current;
}

export function has(key) {
  return key in dictionary.tr;
}

export function t(key, vars) {
  let value = dictionary[current][key] ?? dictionary.tr[key] ?? key;
  if (vars) value = value.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
  return value;
}

export function plural(key, count, vars = {}) {
  const category = new Intl.PluralRules(current).select(count) === "one" ? "one" : "other";
  return t(`${key}.${category}`, { n: count, ...vars });
}

export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-html]")) node.innerHTML = t(node.dataset.i18nHtml);
  for (const node of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of node.dataset.i18nAttr.split(";")) {
      const [attribute, key] = pair.split(":");
      if (attribute && key) node.setAttribute(attribute.trim(), t(key.trim()));
    }
  }
  document.title = t("meta.title");
}

export function onLangChange(callback) {
  listeners.add(callback);
}

export function setLang(next, { persist = true } = {}) {
  if (next !== "tr" && next !== "en") return;
  current = next;
  document.documentElement.setAttribute("lang", next);
  if (persist) {
    try {
      localStorage.setItem("patchy-lang", next);
    } catch (error) {
      void error;
    }
  }
  applyTranslations();
  for (const callback of listeners) callback(next);
}
